#!/usr/bin/env python3
"""Raw HIRSCH reference, docs/formats/insel.md and wildlife.md section 3.

VECTORS: decode/lookup LABEL key=value => count=N values=x,y,flags,raw5,goods[/...] encoded=HEX
Lookup also expects present=0|1. '-' means empty bytes/values; payloads=absent
means missing, otherwise payloads is a comma-separated list of HIRSCH payloads.
Only the first payload is selected, as Island::record does; original duplicate
routing is not inferred. No species, figures, time, world mode or draws here.

--self-test runs bundled hand-derived vectors. --corpus GAME_DIR inventories
original SCP/SZE inputs; optional --manifest writes private file hashes/counts.
Exit 0 agree, 1 disagree or malformed corpus, 2 unusable/zero vectors or input.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import struct
import sys


class Malformed(ValueError):
    pass


# Hand-derived from the eight byte positions, never generated by the decoder.
# 34 12 -> 4660, cd ab -> 43981, raw 82/f3 -> 130/243, 78 56 -> 22136.
BUNDLED = '''
decode distinct payload=3412cdab82f37856 => count=1 values=4660,43981,130,243,22136 encoded=3412cdab82f37856
# All-zero bytes remain a present raw record.
decode zero payload=0000000000000000 => count=1 values=0,0,0,0,0 encoded=0000000000000000
# Complete u16/u8 maxima, including every unknown flag bit.
decode maximum payload=ffffffffffffffff => count=1 values=65535,65535,255,255,65535 encoded=ffffffffffffffff
# No eight-byte entry, distinct from a missing HIRSCH header.
decode empty payload=- => count=0 values=- encoded=-
# File order is distinct then zero, without chunk prepend/reversal here.
decode ordered payload=3412cdab82f378560000000000000000 => count=2 values=4660,43981,130,243,22136/0,0,0,0,0 encoded=3412cdab82f378560000000000000000
lookup missing payloads=absent => present=0 count=0 values=- encoded=-
lookup empty payloads=- => present=1 count=0 values=- encoded=-
# First payload wins even when a later duplicate differs.
lookup first payloads=3412cdab82f37856,0000000000000000 => present=1 count=1 values=4660,43981,130,243,22136 encoded=3412cdab82f37856
# An empty first payload is not skipped in favour of the later record.
lookup first_empty payloads=-,3412cdab82f37856 => present=1 count=0 values=- encoded=-
'''


def integer(value, maximum):
    if not re.fullmatch(r'[0-9]+', value):
        raise Malformed('expected unsigned integer')
    result = int(value)
    if result > maximum:
        raise Malformed('integer out of range')
    return result


def raw(value):
    if value == '-':
        return b''
    if not re.fullmatch(r'(?:[0-9a-fA-F]{2})+', value):
        raise Malformed('expected complete hex bytes or -')
    return bytes.fromhex(value)


def decode(payload):
    if len(payload) % 8:
        raise Malformed('HIRSCH payload length is not a multiple of 8')
    # Python transcription of the documented fields; not generated from C++.
    return [struct.unpack_from('<HHBBH', payload, offset)
            for offset in range(0, len(payload), 8)]


def encode(records):
    return b''.join(struct.pack('<HHBBH', *row) for row in records)


def values(value):
    if value == '-':
        return []
    result = []
    for token in value.split('/'):
        fields = token.split(',')
        if len(fields) != 5:
            raise Malformed('expected five raw fields per record')
        result.append(tuple(integer(x, maximum) for x, maximum in
                            zip(fields, (65535, 65535, 255, 255, 65535))))
    return result


def fields(tokens):
    result = {}
    for token in tokens:
        if token.count('=') != 1:
            raise Malformed('expected key=value')
        key, value = token.split('=')
        if key in result:
            raise Malformed('duplicate field ' + key)
        result[key] = value
    return result


def evaluate(kind, supplied):
    key = {'decode': 'payload', 'lookup': 'payloads'}.get(kind)
    if key is None:
        raise Malformed('unknown record type ' + kind)
    if set(supplied) != {key}:
        raise Malformed('input keys differ')
    if kind == 'decode':
        selected = raw(supplied[key])
    elif supplied[key] == 'absent':
        selected = None
    else:
        payloads = [raw(x) for x in supplied[key].split(',')]
        selected = payloads[0]
    rows = [] if selected is None else decode(selected)
    result = dict(count=len(rows), values=rows, encoded=encode(rows))
    if kind == 'lookup':
        result['present'] = int(selected is not None)
    return result


def vectors(text):
    checked = disagreements = 0
    for line_number, line in enumerate(text.splitlines(), 1):
        line = line.split('#', 1)[0].strip()
        if not line:
            continue
        if line.count('=>') != 1:
            raise Malformed(f'line {line_number}: expected one =>')
        left, right = line.split('=>')
        tokens = left.split()
        if len(tokens) < 3:
            raise Malformed('expected TYPE LABEL and inputs')
        kind, label = tokens[:2]
        actual = evaluate(kind, fields(tokens[2:]))
        expected = fields(right.split())
        if set(actual) != set(expected):
            raise Malformed('output keys differ')
        parsers = {'count': lambda x: integer(x, 0xffffffff), 'values': values,
                   'encoded': raw, 'present': lambda x: integer(x, 1)}
        for key in actual:
            wanted = parsers[key](expected[key])
            if wanted != actual[key]:
                print(f'{label} {key}: expected {wanted!r}, got {actual[key]!r}')
                disagreements += 1
        checked += 1
    if not checked:
        raise Malformed('zero vectors')
    print(f'wildlife load reference: {checked} vectors, {disagreements} disagreements')
    return int(disagreements != 0)


def corpus(game, manifest=None):
    sys.dont_write_bytecode = True
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import insel  # Existing independent chunk/island reader, not C++ output.
    scenes = game / 'Scenes'
    files = sorted((p for p in scenes.rglob('*') if p.suffix.lower() in ('.sze', '.scp')),
                   key=lambda p: p.relative_to(scenes).as_posix())
    if not files:
        raise Malformed('zero corpus files')
    totals = dict(files=0, islands=0, absent=0, empty=0, headers=0, records=0,
                  selected_records=0, malformed=0, duplicate_islands=0, jitter_entries=0)
    by_kind = {}
    inputs = []
    canonical = bytearray()
    for path in files:
        data = path.read_bytes()
        try:
            islands = insel.islands(data)
        except insel.Bad as error:
            raise Malformed('island parse: ' + str(error)) from error
        name = path.relative_to(scenes).as_posix()
        encoded_name = name.encode('utf-8')
        canonical += struct.pack('<I', len(encoded_name)) + encoded_name
        canonical += struct.pack('<I', len(islands))
        counts = {k: 0 for k in totals}
        counts['files'] = 1
        counts['islands'] = len(islands)
        for index, island in enumerate(islands):
            payloads = [p for n, p in island['records'] if n == 'HIRSCH']
            counts['headers'] += len(payloads)
            counts['absent'] += int(not payloads)
            counts['empty'] += int(bool(payloads) and not payloads[0])
            counts['duplicate_islands'] += int(len(payloads) > 1)
            for payload in payloads:
                if len(payload) % 8:
                    counts['malformed'] += 1
                else:
                    counts['records'] += len(decode(payload))
            selected = None if not payloads else payloads[0]
            rows = [] if selected is None or len(selected) % 8 else decode(selected)
            counts['selected_records'] += len(rows)
            counts['jitter_entries'] += sum(not (row[2] & 1) for row in rows)
            canonical += struct.pack('<IBI', index, int(selected is not None), len(rows))
            canonical += encode(rows)
        for key in totals:
            totals[key] += counts[key]
        kind = path.suffix.lower()[1:]
        category = by_kind.setdefault(kind, {k: 0 for k in totals})
        for key in totals:
            category[key] += counts[key]
        inputs.append(dict(file=name, sha256=hashlib.sha256(data).hexdigest(), **counts))
    result = dict(totals=totals, by_kind=by_kind, digest=hashlib.sha256(canonical).hexdigest())
    if manifest:
        try:
            manifest.resolve().relative_to(game.resolve())
        except ValueError:
            pass
        else:
            raise Malformed('manifest must be outside read-only game files')
        manifest.write_text(json.dumps(dict(summary=result, inputs=inputs), indent=2) + '\n',
                            encoding='utf-8')
    print(json.dumps(result, sort_keys=True))
    return int(totals['malformed'] != 0)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('vectors', nargs='?', type=Path)
    parser.add_argument('--self-test', action='store_true')
    parser.add_argument('--corpus', type=Path)
    parser.add_argument('--check-corpus', action='store_true',
                        help='use ANNO1503_GAME_DIR; skip explicitly when unset')
    parser.add_argument('--manifest', type=Path)
    args = parser.parse_args()
    try:
        if args.check_corpus:
            if args.corpus or args.self_test or args.vectors:
                raise Malformed('choose one reference mode')
            game = os.environ.get('ANNO1503_GAME_DIR')
            if not game:
                print('skipping wildlife load corpus: ANNO1503_GAME_DIR not set')
                return 0
            return corpus(Path(game), args.manifest)
        if args.corpus:
            if args.self_test or args.vectors:
                raise Malformed('choose vectors, --self-test or --corpus')
            return corpus(args.corpus, args.manifest)
        if args.manifest or (args.self_test == (args.vectors is not None)):
            raise Malformed('choose vectors, --self-test or --corpus')
        return vectors(BUNDLED if args.self_test else args.vectors.read_text(encoding='utf-8'))
    except (Malformed, OSError, UnicodeError, struct.error, ValueError) as error:
        print('ERROR: ' + str(error), file=sys.stderr)
        return 2


if __name__ == '__main__':
    sys.exit(main())

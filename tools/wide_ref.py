"""Independent big-integer reference for src/sim/include/anno/sim/wide.hpp (MAP-NAV-2 package B).

  wide_ref.py --write <file>   regenerate the vector file with Python integers (the only oracle)
  wide_ref.py --check <file>   verify that the file equals the regeneration
Records (hex, one per line):  mul A B | HI LO     shr HI LO N | HI LO     div HI LO D | QHI QLO R     fdiv A D | Q  (A signed decimal)
add HI LO HI2 LO2 | HI LO CARRY
"""
import sys

M64 = (1 << 64) - 1
M128 = (1 << 128) - 1


def split(v):
    return (v >> 64) & M64, v & M64


EDGES = [0, 1, 2, 3, 0xFF, 0xFFFF, 0x7FFFFFFF, 0x80000000, 0xFFFFFFFF, 0x100000000, 0x1FFFFFFFF, (1 << 51) - 1, 1 << 51,
         (1 << 63) - 1, 1 << 63, (1 << 63) + 1, M64 - 1, M64, 11863283, 11863283 << 9, 42949672, 500 * (1 << 24)]


def records():
    out = []
    for a in EDGES:
        for b in EDGES:
            hi, lo = split(a * b)
            out.append('mul %x %x | %x %x' % (a, b, hi, lo))
    vals = [0, 1, 5, M64, 1 << 64, (1 << 64) + 7, (1 << 75) + 12345, (1 << 86) - 1, M128, M128 - 1, (1 << 127), (1 << 127) - 1]
    for v in vals:
        for n in (0, 1, 24, 31, 32, 63, 64, 65, 100, 127, 128):
            hi, lo = split(v >> n if n < 128 else 0)
            h, l = split(v)
            out.append('shr %x %x %d | %x %x' % (h, l, n, hi, lo))
    for v in vals:
        for d in (1, 2, 3, 5, 500, 500 * (1 << 24), 11863283, 1 << 35, (1 << 35) + 1, (1 << 63) - 1, 1 << 63, (1 << 63) + 1, M64):
            q, r = divmod(v, d)
            h, l = split(v)
            qh, ql = split(q)
            out.append('div %x %x %x | %x %x %x' % (h, l, d, qh, ql, r))
    for x in vals[:8]:
        for y in vals[4:]:
            s = x + y
            h, l = split(x)
            h2, l2 = split(y)
            sh, sl = split(s & M128)
            out.append('add %x %x %x %x | %x %x %d' % (h, l, h2, l2, sh, sl, 1 if s > M128 else 0))
    for a in (0, 1, -1, 499, -499, 500, -500, 12345678901234, -12345678901234, (1 << 62), -(1 << 62), -(1 << 63) + 1):
        for d in (1, 2, 500 * (1 << 24), 500, 3):
            out.append('fdiv %d %d | %d' % (a, d, a // d))
    return out


def main():
    if len(sys.argv) != 3 or sys.argv[1] not in ('--write', '--check'):
        print(__doc__)
        return 2
    text = '# Generated by tools/wide_ref.py from Python big integers (the only oracle). Do not edit.\n' + '\n'.join(records()) + '\n'
    if sys.argv[1] == '--write':
        open(sys.argv[2], 'w').write(text)
        return 0
    ok = open(sys.argv[2]).read() == text
    print('wide vectors', 'agree' if ok else 'DIFFER')
    return 0 if ok else 1


if __name__ == '__main__':
    sys.exit(main())
